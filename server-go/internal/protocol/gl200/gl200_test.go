func TestJavaTextDecoder(t *testing.T) {
	oracle.Run(t, "Gl200TextProtocolDecoderTest", oracle.Handlers{
		Decoder: func(_ string, env *oracle.Env) ingest.Decoder {
			return &TextDecoder{Options: ReadOptions(env.Cfg, "unknown")}
		},
	})
}

func TestJavaBinaryDecoder(t *testing.T) {
	oracle.Run(t, "Gl200BinaryProtocolDecoderTest", oracle.Handlers{
		Decoder: func(string, *oracle.Env) ingest.Decoder { return ingest.DecoderFunc(DecodeBinary) },
	})
}

