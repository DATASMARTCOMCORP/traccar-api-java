// Command gen writes all.go: every protocol package under internal/protocol, registered by
// the shape of its Protocol constructor.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

var shapes = []struct {
	re   *regexp.Regexp
	expr string
}{
	{regexp.MustCompile(`func Protocol\(\) ingest\.Protocol`), "fixed(%s.Protocol)"},
	{regexp.MustCompile(`func Protocol\(cfg \*config\.Config\) \(ingest\.Protocol, error\)`), "withConfig(%s.Protocol)"},
	{regexp.MustCompile(`func Protocol\(cfg \*config\.Config, zone \*time\.Location\) \(ingest\.Protocol, error\)`), "%s.Protocol"},
}

func main() {
	dirs, err := os.ReadDir("..")
	if err != nil {
		log.Fatal(err)
	}
	var names []string
	exprs := map[string]string{}
	for _, d := range dirs {
		name := d.Name()
		if !d.IsDir() || name == "kit" || name == "oracle" || name == "all" {
			continue
		}
		files, _ := filepath.Glob(filepath.Join("..", name, "*.go"))
		var src strings.Builder
		for _, f := range files {
			if !strings.HasSuffix(f, "_test.go") {
				b, err := os.ReadFile(f)
				if err != nil {
					log.Fatal(err)
				}
				src.Write(b)
			}
		}
		for _, s := range shapes {
			if s.re.MatchString(src.String()) {
				exprs[name] = fmt.Sprintf(s.expr, name)
				break
			}
		}
		if exprs[name] == "" {
			log.Fatalf("%s: no Protocol constructor", name)
		}
		names = append(names, name)
	}
	sort.Strings(names)

	var b bytes.Buffer
	b.WriteString(`// Code generated by gen; DO NOT EDIT.

// Package all lists the ported device protocols, for the server to start them.
package all

import (
	"sort"
	"time"

	"github.com/DATASMARTCOMCORP/traccar-api-java/server-go/internal/config"
	"github.com/DATASMARTCOMCORP/traccar-api-java/server-go/internal/ingest"
`)
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q\n", "github.com/DATASMARTCOMCORP/traccar-api-java/server-go/internal/protocol/"+n)
	}
	b.WriteString(`)

// A Constructor makes a protocol's definition from the configuration; zone is the
// server's time zone (Java's default zone).
type Constructor func(cfg *config.Config, zone *time.Location) (ingest.Protocol, error)

func fixed(p func() ingest.Protocol) Constructor {
	return func(*config.Config, *time.Location) (ingest.Protocol, error) { return p(), nil }
}

func withConfig(p func(*config.Config) (ingest.Protocol, error)) Constructor {
	return func(cfg *config.Config, _ *time.Location) (ingest.Protocol, error) { return p(cfg) }
}

// protocols are the ported protocols by name (Java's BaseProtocol.getName).
var protocols = map[string]Constructor{
`)
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q: %s,\n", n, exprs[n])
	}
	b.WriteString(`}

// Names returns the ported protocols' names, sorted.
func Names() []string {
	var names []string
	for name := range protocols {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

// Lookup returns a protocol's constructor.
func Lookup(name string) (Constructor, bool) {
	c, ok := protocols[name]
	return c, ok
}
`)
	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("all.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}
