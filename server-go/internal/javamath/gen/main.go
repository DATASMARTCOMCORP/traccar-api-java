// Command gen translates HotSpot's x86_64 sin and cos stubs (the code Java 21 runs for
// Math.sin and Math.cos on x86_64) into Go code that executes them instruction by
// instruction on the emulated machine in x86.go, so Go gets Java's exact results.
//
// It reads the stub sources of the JDK production runs (MIGRATION.md §8: Corretto 21.0.12,
// which builds OpenJDK jdk-21.0.12+8 unchanged in these files):
//
//	https://github.com/openjdk/jdk21u/raw/jdk-21.0.12+8/src/hotspot/cpu/x86/stubGenerator_x86_64_constants.cpp
//	https://github.com/openjdk/jdk21u/raw/jdk-21.0.12+8/src/hotspot/cpu/x86/stubGenerator_x86_64_sin.cpp
//	https://github.com/openjdk/jdk21u/raw/jdk-21.0.12+8/src/hotspot/cpu/x86/stubGenerator_x86_64_cos.cpp
//
// Usage: go run ./gen -src DIR > libm_gen.go (DIR holds the three files).
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

func main() {
	src := flag.String("src", "", "directory with the HotSpot stub sources")
	flag.Parse()
	read := func(name string) string {
		b, err := os.ReadFile(filepath.Join(*src, name))
		if err != nil {
			log.Fatal(err)
		}
		return string(b)
	}
	constants := read("stubGenerator_x86_64_constants.cpp")
	sin := read("stubGenerator_x86_64_sin.cpp")
	cos := read("stubGenerator_x86_64_cos.cpp")

	g := &gen{tables: map[string]int{}}
	g.addTables(constants)
	g.addTables(sin)
	g.addTables(cos)

	var body bytes.Buffer
	g.out = &body
	g.function("libmSin", "generate_libmSin", sin)
	g.function("libmCos", "generate_libmCos", cos)

	var file bytes.Buffer
	fmt.Fprintf(&file, "// Code generated by gen from HotSpot jdk-21.0.12+8 stubGenerator_x86_64_{constants,sin,cos}.cpp; DO NOT EDIT.\n\n")
	fmt.Fprintf(&file, "%s\n", license(sin))
	fmt.Fprintf(&file, "package javamath\n\n")
	fmt.Fprintf(&file, "// Addresses of the stub tables in the emulated memory.\nconst (\n")
	names := make([]string, 0, len(g.tables))
	for name := range g.tables {
		names = append(names, name)
	}
	sort.Slice(names, func(i, j int) bool { return g.tables[names[i]] < g.tables[names[j]] })
	for _, name := range names {
		fmt.Fprintf(&file, "\taddr%s = imageBase + %d\n", name, g.tables[name])
	}
	fmt.Fprintf(&file, ")\n\n// image is the stub tables' memory, as little-endian 32-bit words.\nvar image = [...]uint32{\n")
	for i, w := range g.image {
		if i%6 == 0 {
			file.WriteString("\t")
		}
		fmt.Fprintf(&file, "0x%08x,", w)
		if i%6 == 5 || i == len(g.image)-1 {
			file.WriteString("\n")
		} else {
			file.WriteString(" ")
		}
	}
	fmt.Fprintf(&file, "}\n\n")
	file.Write(body.Bytes())
	out, err := format.Source(file.Bytes())
	if err != nil {
		os.Stdout.Write(file.Bytes())
		log.Fatal(err)
	}
	os.Stdout.Write(out)
}

// license returns the stub sources' copyright header as Go comments.
func license(src string) string {
	end := strings.Index(src, "*/")
	var b strings.Builder
	b.WriteString("// The tables and code below are translated from HotSpot sources under this notice:\n//\n")
	for _, line := range strings.Split(strings.TrimSpace(src[:end]), "\n")[1:] {
		line = strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(line), "*"))
		b.WriteString(strings.TrimRight("// "+line, " ") + "\n")
	}
	return b.String()
}

type gen struct {
	tables map[string]int // table name to byte offset in image
	image  []uint32
	out    *bytes.Buffer
}

var tableRE = regexp.MustCompile(`(?s)ATTRIBUTE_ALIGNED\((\d+)\) static const juint _(\w+)\[\] =\s*\{(.*?)\};`)

func (g *gen) addTables(src string) {
	for _, m := range tableRE.FindAllStringSubmatch(src, -1) {
		// Every table starts 16-byte aligned, after a 16-byte gap.
		for len(g.image)%4 != 0 {
			g.image = append(g.image, 0)
		}
		g.image = append(g.image, 0, 0, 0, 0)
		g.tables[m[2]] = len(g.image) * 4
		for _, w := range strings.Split(m[3], ",") {
			w = strings.TrimSpace(strings.TrimSuffix(strings.TrimSpace(w), "UL"))
			if w == "" {
				continue
			}
			v, err := strconv.ParseUint(w, 0, 32)
			if err != nil {
				log.Fatalf("table %s: %v", m[2], err)
			}
			g.image = append(g.image, uint32(v))
		}
	}
}

var (
	instrRE   = regexp.MustCompile(`^__ (\w+)\((.*)\);$`)
	commentRE = regexp.MustCompile(`/\*.*?\*/|//.*$`)
	regs      = map[string]int{"rax": 0, "rcx": 1, "rdx": 2, "rbx": 3, "rsp": 4, "rbp": 5, "rsi": 6, "rdi": 7,
		"r8": 8, "r9": 9, "r10": 10, "r11": 11, "r12": 12, "r13": 13, "r14": 14, "r15": 15}
	conds = map[string]string{
		"above": "!m.cf && !m.zf", "aboveEqual": "!m.cf", "below": "m.cf", "belowEqual": "m.cf || m.zf",
		"equal": "m.zf", "notEqual": "!m.zf", "greater": "!m.zf && m.sf == m.of", "greaterEqual": "m.sf == m.of",
		"less": "m.sf != m.of", "lessEqual": "m.zf || m.sf != m.of", "negative": "m.sf", "positive": "!m.sf",
	}
)

type operand struct {
	kind  string // reg, xmm, mem, imm, cond, label
	n     int    // register number
	addr  string // Go expression of a memory address
	imm   int64
	label string
}

// function translates one stub generator into a Go function of the emulated machine.
func (g *gen) function(name, generator, src string) {
	start := strings.Index(src, generator+"() {")
	if start < 0 {
		log.Fatalf("%s not found", generator)
	}
	lines := strings.Split(src[start:], "\n")
	var code []string
	targets := map[string]bool{}
	skip := []bool{} // stack of skipping states for #ifdef and if/else blocks
	skipping := func() bool {
		for _, s := range skip {
			if s {
				return true
			}
		}
		return false
	}
	for _, line := range lines[1:] {
		line = strings.TrimSpace(commentRE.ReplaceAllString(line, ""))
		switch {
		case line == "return start;":
			goto done
		case line == "#ifdef _WIN64":
			skip = append(skip, true)
			continue
		case line == "#endif":
			skip = skip[:len(skip)-1]
			continue
		case line == "if (VM_Version::supports_sse3()) {":
			// Production's CPUs (Xeon 8259CL) have SSE3.
			skip = append(skip, false)
			continue
		case line == "} else {":
			skip[len(skip)-1] = !skip[len(skip)-1]
			continue
		case line == "}":
			skip = skip[:len(skip)-1]
			continue
		case line == "", strings.HasPrefix(line, "Label "), strings.HasPrefix(line, "StubCodeMark "),
			strings.HasPrefix(line, "address "):
			continue
		}
		if skipping() {
			continue
		}
		m := instrRE.FindStringSubmatch(line)
		if m == nil {
			log.Fatalf("%s: unexpected line %q", name, line)
		}
		ops := g.operands(m[2])
		if m[1] == "jcc" || m[1] == "jmp" {
			targets[ops[len(ops)-1].label] = true
		}
		code = append(code, g.instr(m[1], ops))
	}
	log.Fatalf("%s: no end", name)
done:
	fmt.Fprintf(g.out, "func %s(x float64) float64 {\n\tm := newMachine(x)\n", name)
	for _, c := range code {
		if strings.HasSuffix(c, ":") && !targets[strings.TrimSuffix(c, ":")] {
			continue
		}
		fmt.Fprintf(g.out, "%s\n", c)
	}
	fmt.Fprintf(g.out, "}\n\n")
}

func splitArgs(s string) []string {
	var args []string
	depth, from := 0, 0
	for i, c := range s {
		switch c {
		case '(':
			depth++
		case ')':
			depth--
		case ',':
			if depth == 0 {
				args = append(args, strings.TrimSpace(s[from:i]))
				from = i + 1
			}
		}
	}
	if strings.TrimSpace(s[from:]) != "" {
		args = append(args, strings.TrimSpace(s[from:]))
	}
	return args
}

var (
	addressRE  = regexp.MustCompile(`^Address\((\w+), (-?\d+)\)$`)
	externalRE = regexp.MustCompile(`^ExternalAddress\((\w+)(?: \+ (\d+))?\)$`)
)

func (g *gen) operands(s string) []operand {
	args := splitArgs(s)
	// A scratch register follows external memory operands: drop it.
	if n := len(args); n >= 2 && strings.HasPrefix(args[n-2], "ExternalAddress(") {
		if _, ok := regs[args[n-1]]; ok {
			args = args[:n-1]
		}
	}
	var ops []operand
	for _, a := range args {
		var op operand
		if n, ok := regs[a]; ok {
			op = operand{kind: "reg", n: n}
		} else if strings.HasPrefix(a, "xmm") {
			n, err := strconv.Atoi(a[3:])
			if err != nil {
				log.Fatalf("bad operand %q", a)
			}
			op = operand{kind: "xmm", n: n}
		} else if m := addressRE.FindStringSubmatch(a); m != nil {
			r, ok := regs[m[1]]
			if !ok {
				log.Fatalf("bad base %q", a)
			}
			op = operand{kind: "mem", addr: fmt.Sprintf("m.r[%d]+%s", r, m[2])}
			if strings.HasPrefix(m[2], "-") {
				op.addr = fmt.Sprintf("m.r[%d]-%s", r, m[2][1:])
			}
		} else if m := externalRE.FindStringSubmatch(a); m != nil {
			if _, ok := g.tables[m[1]]; !ok {
				log.Fatalf("unknown table %q", m[1])
			}
			op = operand{kind: "mem", addr: "addr" + m[1]}
			if m[2] != "" {
				op.addr += "+" + m[2]
			}
		} else if strings.HasPrefix(a, "Assembler::") {
			c := strings.TrimPrefix(a, "Assembler::")
			if _, ok := conds[c]; !ok {
				log.Fatalf("unknown condition %q", a)
			}
			op = operand{kind: "cond", label: c}
		} else if a == "INT_MIN" {
			op = operand{kind: "imm", imm: -1 << 31}
		} else if v, err := strconv.ParseInt(a, 0, 64); err == nil {
			op = operand{kind: "imm", imm: v}
		} else if u, err := strconv.ParseUint(a, 0, 64); err == nil {
			op = operand{kind: "imm", imm: int64(u)}
		} else if regexp.MustCompile(`^[A-Za-z_]\w*$`).MatchString(a) {
			op = operand{kind: "label", label: a}
		} else {
			log.Fatalf("bad operand %q", a)
		}
		ops = append(ops, op)
	}
	return ops
}

func kinds(ops []operand) string {
	k := make([]string, len(ops))
	for i, o := range ops {
		k[i] = o.kind
	}
	return strings.Join(k, ",")
}

// src32 and src64 are Go expressions for an integer source operand.
func src32(o operand) string {
	switch o.kind {
	case "reg":
		return fmt.Sprintf("uint32(m.r[%d])", o.n)
	case "imm":
		return fmt.Sprintf("uint32(0x%x)", uint32(o.imm))
	case "mem":
		return fmt.Sprintf("m.load32(%s)", o.addr)
	}
	log.Fatalf("bad 32-bit source %+v", o)
	return ""
}

func src64(o operand) string {
	switch o.kind {
	case "reg":
		return fmt.Sprintf("m.r[%d]", o.n)
	case "imm":
		return fmt.Sprintf("uint64(0x%x)", uint64(o.imm))
	case "mem":
		return fmt.Sprintf("m.load64(%s)", o.addr)
	}
	log.Fatalf("bad 64-bit source %+v", o)
	return ""
}

// srcLow is the low 64-bit lane of an SSE source; srcPair both lanes.
func srcLow(o operand) string {
	switch o.kind {
	case "xmm":
		return fmt.Sprintf("m.x[%d][0]", o.n)
	case "mem":
		return fmt.Sprintf("m.load64(%s)", o.addr)
	}
	log.Fatalf("bad SSE source %+v", o)
	return ""
}

func srcPair(o operand) string {
	switch o.kind {
	case "xmm":
		return fmt.Sprintf("m.x[%d]", o.n)
	case "mem":
		return fmt.Sprintf("m.load128(%s)", o.addr)
	}
	log.Fatalf("bad SSE source %+v", o)
	return ""
}

var (
	alu = map[string]string{"add": "add", "sub": "sub", "and": "and", "or": "or", "xor": "xor",
		"cmp": "sub", "test": "and", "sbb": "sbb"}
	sse = map[string]string{"add": "+", "sub": "-", "mul": "*", "div": "/"}
)

func (g *gen) instr(op string, ops []operand) string {
	k := kinds(ops)
	bad := func() string {
		log.Fatalf("unsupported %s(%s) %+v", op, k, ops)
		return ""
	}
	switch op {
	case "bind":
		return ops[0].label + ":"
	case "jmp":
		return "goto " + ops[0].label
	case "jcc":
		return fmt.Sprintf("if %s {\ngoto %s\n}", conds[ops[0].label], ops[1].label)
	case "enter":
		return "m.push(m.r[5])\nm.r[5] = m.r[4]"
	case "leave":
		return "m.r[4] = m.r[5]\nm.r[5] = m.pop()"
	case "ret":
		return "return m.result()"
	case "push":
		return fmt.Sprintf("m.push(%s)", src64(ops[0]))
	case "pop":
		return fmt.Sprintf("m.r[%d] = m.pop()", ops[0].n)
	case "mov64":
		return fmt.Sprintf("m.r[%d] = %s", ops[0].n, src64(ops[1]))
	case "lea":
		if k != "reg,mem" {
			return bad()
		}
		return fmt.Sprintf("m.r[%d] = %s", ops[0].n, ops[1].addr)
	case "movl":
		switch k {
		case "reg,reg", "reg,imm", "reg,mem":
			return fmt.Sprintf("m.r[%d] = uint64(%s)", ops[0].n, src32(ops[1]))
		case "mem,reg":
			return fmt.Sprintf("m.store32(%s, %s)", ops[0].addr, src32(ops[1]))
		}
	case "movq", "movdq", "movsd":
		switch k {
		case "reg,reg", "reg,mem":
			return fmt.Sprintf("m.r[%d] = %s", ops[0].n, src64(ops[1]))
		case "reg,xmm":
			return fmt.Sprintf("m.r[%d] = m.x[%d][0]", ops[0].n, ops[1].n)
		case "xmm,reg":
			return fmt.Sprintf("m.x[%d] = [2]uint64{m.r[%d], 0}", ops[0].n, ops[1].n)
		case "xmm,mem":
			return fmt.Sprintf("m.x[%d] = [2]uint64{%s, 0}", ops[0].n, srcLow(ops[1]))
		case "xmm,xmm":
			if op == "movsd" { // register-to-register movsd keeps the upper lane
				return fmt.Sprintf("m.x[%d][0] = m.x[%d][0]", ops[0].n, ops[1].n)
			}
			return fmt.Sprintf("m.x[%d] = [2]uint64{m.x[%d][0], 0}", ops[0].n, ops[1].n)
		case "mem,xmm":
			return fmt.Sprintf("m.store64(%s, m.x[%d][0])", ops[0].addr, ops[1].n)
		case "mem,reg":
			return fmt.Sprintf("m.store64(%s, m.r[%d])", ops[0].addr, ops[1].n)
		}
	case "movdqu":
		switch k {
		case "xmm,xmm", "xmm,mem":
			return fmt.Sprintf("m.x[%d] = %s", ops[0].n, srcPair(ops[1]))
		case "mem,xmm":
			return fmt.Sprintf("m.store128(%s, m.x[%d])", ops[0].addr, ops[1].n)
		}
	case "addsd", "subsd", "mulsd", "divsd":
		if ops[0].kind != "xmm" || len(ops) != 2 {
			return bad()
		}
		d := fmt.Sprintf("m.x[%d][0]", ops[0].n)
		return fmt.Sprintf("%s = sd(%s %s %s)", d, f(d), sse[op[:3]], f(srcLow(ops[1])))
	case "addpd", "subpd", "mulpd", "divpd":
		if ops[0].kind != "xmm" || len(ops) != 2 {
			return bad()
		}
		d := fmt.Sprintf("m.x[%d]", ops[0].n)
		return fmt.Sprintf("m.x[%d] = pd(%s, %s, func(a, b float64) float64 { return a %s b })", ops[0].n, d, srcPair(ops[1]), sse[op[:3]])
	case "xorpd", "pand", "por", "pxor", "andpd", "orpd":
		bop := map[string]string{"xorpd": "^", "pxor": "^", "pand": "&", "andpd": "&", "por": "|", "orpd": "|"}[op]
		return fmt.Sprintf("{\ns := %s\nm.x[%d][0] %s= s[0]\nm.x[%d][1] %s= s[1]\n}", srcPair(ops[1]), ops[0].n, bop, ops[0].n, bop)
	case "unpcklpd":
		return fmt.Sprintf("m.x[%d][1] = %s[0]", ops[0].n, srcPair(ops[1]))
	case "unpckhpd":
		return fmt.Sprintf("m.x[%d] = [2]uint64{m.x[%d][1], %s[1]}", ops[0].n, ops[0].n, srcPair(ops[1]))
	case "movlhps":
		return fmt.Sprintf("m.x[%d][1] = m.x[%d][0]", ops[0].n, ops[1].n)
	case "movddup":
		return fmt.Sprintf("m.x[%d] = [2]uint64{%s, %s}", ops[0].n, srcLow(ops[1]), srcLow(ops[1]))
	case "pshufd":
		return fmt.Sprintf("m.x[%d] = pshufd(%s, %d)", ops[0].n, srcPair(ops[1]), ops[2].imm)
	case "pextrw":
		return fmt.Sprintf("m.r[%d] = pextrw(m.x[%d], %d)", ops[0].n, ops[1].n, ops[2].imm)
	case "pinsrw":
		return fmt.Sprintf("m.x[%d] = pinsrw(m.x[%d], m.r[%d], %d)", ops[0].n, ops[0].n, ops[1].n, ops[2].imm)
	case "cvttsd2sil":
		return fmt.Sprintf("m.r[%d] = uint64(cvttsd2si32(%s))", ops[0].n, f(srcLow(ops[1])))
	case "cvttsd2siq":
		return fmt.Sprintf("m.r[%d] = cvttsd2si64(%s)", ops[0].n, f(srcLow(ops[1])))
	case "cvtsi2sdl":
		return fmt.Sprintf("m.x[%d][0] = sd(float64(int32(%s)))", ops[0].n, src32(ops[1]))
	case "cvtsi2sdq":
		return fmt.Sprintf("m.x[%d][0] = sd(float64(int64(%s)))", ops[0].n, src64(ops[1]))
	case "bsrq":
		return fmt.Sprintf("m.bsr(%d, %s)", ops[0].n, src64(ops[1]))
	case "imulq":
		if k != "reg,reg" {
			return bad()
		}
		return fmt.Sprintf("m.r[%d] = m.imul64(m.r[%d], m.r[%d])", ops[0].n, ops[0].n, ops[1].n)
	case "negl":
		return fmt.Sprintf("m.r[%d] = uint64(m.sub32(0, uint32(m.r[%d])))", ops[0].n, ops[0].n)
	case "negq":
		return fmt.Sprintf("m.r[%d] = m.sub64(0, m.r[%d])", ops[0].n, ops[0].n)
	}
	if len(op) >= 3 && (strings.HasSuffix(op, "l") || strings.HasSuffix(op, "q")) {
		base, w := op[:len(op)-1], op[len(op)-1:]
		if ops[0].kind != "reg" {
			return bad()
		}
		d := ops[0].n
		switch base {
		case "shl", "shr", "sar":
			count := fmt.Sprintf("uint(m.r[1])") // by cl
			if len(ops) == 2 {
				count = fmt.Sprintf("uint(%d)", ops[1].imm)
			}
			if w == "l" {
				return fmt.Sprintf("m.r[%d] = uint64(m.%s32(uint32(m.r[%d]), %s))", d, base, d, count)
			}
			return fmt.Sprintf("m.r[%d] = m.%s64(m.r[%d], %s)", d, base, d, count)
		}
		if fn, ok := alu[base]; ok && len(ops) == 2 {
			call := fmt.Sprintf("m.%s64(m.r[%d], %s)", fn, d, src64(ops[1]))
			if w == "l" {
				call = fmt.Sprintf("m.%s32(uint32(m.r[%d]), %s)", fn, d, src32(ops[1]))
			}
			switch {
			case base == "cmp" || base == "test": // flags only
				return call
			case w == "l": // 32-bit results clear the upper half
				return fmt.Sprintf("m.r[%d] = uint64(%s)", d, call)
			}
			return fmt.Sprintf("m.r[%d] = %s", d, call)
		}
	}
	return bad()
}

// f is the float64 value of a lane expression.
func f(lane string) string { return "fl(" + lane + ")" }
